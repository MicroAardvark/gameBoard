// lib/models/chat_message.dart

/// A single message in the in-game chat, produced either by a user or by the
/// server (e.g. "Player 2 joined the room").
///
/// [type] controls how the UI renders the message — system messages are
/// typically shown in a distinct style to separate game events from player chat.
class ChatMessage {
  final String id;
  final String? userId; // Null for system-generated messages.
  final String username;
  final String message;
  final DateTime timestamp;
  final ChatMessageType type;

  ChatMessage({
    required this.id,
    this.userId,
    required this.username,
    required this.message,
    required this.timestamp,
    this.type = ChatMessageType.user,
  });

  /// Deserialises a message from the Socket.IO payload.
  ///
  /// [timestamp] arrives as milliseconds since epoch (standard JS Date.now())
  /// and is converted to a Dart [DateTime] for local formatting.
  factory ChatMessage.fromJson(Map<String, dynamic> json) {
    return ChatMessage(
      id:        json['id'] ?? '',
      userId:    json['userId'],
      username:  json['username'] ?? 'Unknown',
      message:   json['message'] ?? '',
      timestamp: DateTime.fromMillisecondsSinceEpoch(json['timestamp']),
      type:      json['type'] == 'system' ? ChatMessageType.system : ChatMessageType.user,
    );
  }

  bool get isSystemMessage => type == ChatMessageType.system;
}

enum ChatMessageType {
  user,   // Sent by a human player.
  system, // Generated by the server for game events (joins, disconnects, etc.).
}